// One-off: rasterises Natural Earth land (world-atlas, 110m) into a 1° bit mask used by the 3D globe.
// Usage: node scripts/gen-land-mask.mjs
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import { readFileSync, writeFileSync } from 'node:fs';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const W = 360, H = 180;
const bytes = new Uint8Array(Math.ceil((W * H) / 8));
let n = 0;
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5);
  for (let x = 0; x < W; x++) {
    const lon = -180 + (x + 0.5);
    if (geoContains(land, [lon, lat])) { const i = y * W + x; bytes[i >> 3] |= 1 << (i & 7); n++; }
  }
}
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync('src/js/land-mask.js', `// Generated by scripts/gen-land-mask.mjs — 1° land mask (360×180, bit-packed, row-major from 90°N / 180°W)\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\nconst B64 = '${b64}';\nconst RAW = Uint8Array.from(atob(B64), (c) => c.charCodeAt(0));\nexport function isLand(lat, lon) {\n  const x = Math.min(LAND_W - 1, Math.max(0, Math.floor(lon + 180)));\n  const y = Math.min(LAND_H - 1, Math.max(0, Math.floor(90 - lat)));\n  const i = y * LAND_W + x;\n  return (RAW[i >> 3] >> (i & 7)) & 1;\n}\n`);
console.log('land cells', n, 'bytes', bytes.length);
